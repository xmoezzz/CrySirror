#!/usr/bin/env python3
"""Generates src/rt/import_aliases.rs: the names each upstream Ren'Py module
binds with top-level `import` / `from ... import` statements, per reference
release.

The native runtime binds these lazily (module `__getattr__`), so
`renpy.display.behavior.render` or `renpy.display.core.pygame` resolve to
the same objects as upstream without import-order cycles.

usage: import_aliases.py REPO API_JSON OUT
  REPO      git clone of github.com/renpy/renpy with the release tags
  API_JSON  {tag: {module: [top-level names]}} of the reference releases;
            only names listed there are emitted.
"""
import json
import re
import subprocess
import sys

TAGS = [
    "6.18.3.761", "6.99.12.4.2187", "7.0.0.196", "7.3.5.606", "7.4.11.2266",
    "7.5.3.22090809", "7.6.3.23091805", "7.8.7.25031702", "8.0.3.22090809",
    "8.1.3.23091805", "8.2.3.24061702", "8.3.7.25031702", "8.4.1.25072401",
    "8.5.3.26051504", "8.6.1.26111705",
]


def git(repo, *args):
    return subprocess.check_output(["git", "-C", repo] + list(args)).decode("utf-8", "replace")


def module_name(path):
    p = path[:-4] if path.endswith((".pyx", ".pxd")) else path[:-3]
    parts = p.split("/")
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def logical_lines(src):
    """Top-level (column 0) import statements, joined across () and \\."""
    lines = src.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.startswith(("import ", "from ")):
            i += 1
            continue
        stmt = line.split("#", 1)[0]
        depth = stmt.count("(") - stmt.count(")")
        while (depth > 0 or stmt.rstrip().endswith("\\")) and i + 1 < len(lines):
            i += 1
            nxt = lines[i].split("#", 1)[0]
            stmt = stmt.rstrip().rstrip("\\") + " " + nxt.strip()
            depth += nxt.count("(") - nxt.count(")")
        yield stmt
        i += 1


def resolve(mod, is_pkg, rel):
    dots = len(rel) - len(rel.lstrip("."))
    rest = rel[dots:]
    if not dots:
        return rest
    base = mod.split(".")
    if not is_pkg:
        base = base[:-1]
    base = base[: len(base) - (dots - 1)]
    return ".".join(base + ([rest] if rest else []))


def aliases(mod, is_pkg, src):
    out = {}
    for stmt in logical_lines(src):
        stmt = stmt.strip()
        m = re.match(r"from\s+(\S+)\s+c?import\s+(.*)$", stmt)
        if m:
            source = resolve(mod, is_pkg, m.group(1))
            if source == "__future__" or m.group(2).strip() == "*":
                continue
            names = m.group(2).replace("(", " ").replace(")", " ")
            for part in names.split(","):
                part = part.strip()
                if not part:
                    continue
                bits = part.split()
                if len(bits) == 3 and bits[1] == "as":
                    out[bits[2]] = (source, bits[0])
                elif len(bits) == 1:
                    out[bits[0]] = (source, bits[0])
            continue
        m = re.match(r"c?import\s+(.*)$", stmt)
        if m:
            for part in m.group(1).split(","):
                bits = part.split()
                if not bits:
                    continue
                if len(bits) == 3 and bits[1] == "as":
                    out[bits[2]] = (bits[0], "")
                elif len(bits) == 1:
                    top = bits[0].split(".")[0]
                    out[top] = (top, "")
    return out


def main():
    repo, api_path, out_path = sys.argv[1:4]
    api = json.load(open(api_path))
    table = {}
    for ti, tag in enumerate(TAGS):
        names_of = api.get(tag, {})
        files = git(repo, "ls-tree", "-r", "--name-only", tag, "renpy").split()
        for f in files:
            if not f.endswith((".py", ".pyx")):
                continue
            mod = module_name(f)
            if mod not in names_of:
                continue
            wanted = set(names_of[mod])
            src = git(repo, "show", "%s:%s" % (tag, f))
            is_pkg = f.endswith(("__init__.py", "__init__.pyx"))
            for name, (source, attr) in aliases(mod, is_pkg, src).items():
                if name not in wanted or source == mod:
                    continue
                key = (mod, name, source, attr)
                table[key] = table.get(key, 0) | (1 << ti)
    rows = sorted(table.items())
    with open(out_path, "w") as f:
        f.write("// SPDX-License-Identifier: MPL-2.0\n")
        f.write("// Generated by tools/import_aliases.py from the upstream Ren'Py sources (MIT).\n")
        f.write("//! Names upstream modules bind by top-level imports, per release:\n")
        f.write("//! (module, name, source module, source attribute or \"\" for the module,\n")
        f.write("//! bit i set when reference release `TAGS[i]` binds it).\n\n")
        f.write("pub const TAGS: [[u32; 3]; %d] = [\n" % len(TAGS))
        for t in TAGS:
            a, b, c = t.split(".")[:3]
            f.write("    [%s, %s, %s],\n" % (a, b, c))
        f.write("];\n\n")
        f.write("pub const ALIASES: &[(&str, &str, &str, &str, u16)] = &[\n")
        for (mod, name, source, attr), mask in rows:
            f.write('    ("%s", "%s", "%s", "%s", 0x%04x),\n' % (mod, name, source, attr, mask))
        f.write("];\n")
    print(len(rows), "aliases")


main()

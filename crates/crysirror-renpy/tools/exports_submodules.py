#!/usr/bin/env python3
"""Generates src/rt/exports/submodules.rs: the top-level names of the
`renpy.exports.*exports` submodules (8.2+) per reference release.

usage: exports_submodules.py API_JSON OUT
"""
import json
import sys

TAGS = [
    "6.18.3.761", "6.99.12.4.2187", "7.0.0.196", "7.3.5.606", "7.4.11.2266",
    "7.5.3.22090809", "7.6.3.23091805", "7.8.7.25031702", "8.0.3.22090809",
    "8.1.3.23091805", "8.2.3.24061702", "8.3.7.25031702", "8.4.1.25072401",
    "8.5.3.26051504", "8.6.1.26111705",
]

api = json.load(open(sys.argv[1]))
rows = {}
mods = {}
for i, tag in enumerate(TAGS):
    for mod, names in api.get(tag, {}).items():
        if not mod.startswith("renpy.exports."):
            continue
        mods[mod] = mods.get(mod, 0) | (1 << i)
        for n in names:
            rows[(mod, n)] = rows.get((mod, n), 0) | (1 << i)
with open(sys.argv[2], "w") as f:
    f.write("// SPDX-License-Identifier: MPL-2.0\n")
    f.write("// Generated by tools/exports_submodules.py from the upstream Ren'Py sources (MIT).\n")
    f.write("//! `renpy.exports.*exports` submodules and their names, per reference release\n")
    f.write("//! (bit i: `aliases::TAGS[i]`).\n\n")
    f.write("pub const MODULES: &[(&str, u16)] = &[\n")
    for m, mask in sorted(mods.items()):
        f.write('    ("%s", 0x%04x),\n' % (m, mask))
    f.write("];\n\npub const NAMES: &[(&str, &str, u16)] = &[\n")
    for (m, n), mask in sorted(rows.items()):
        f.write('    ("%s", "%s", 0x%04x),\n' % (m, n, mask))
    f.write("];\n")
print(len(mods), "modules", len(rows), "names")

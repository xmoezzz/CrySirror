"""Generates src/rt/preference_tables.rs from a Ren'Py checkout: the
Preference(...) list and Preferences.__version__ offset of the newest tag of
every 7.x/8.x minor release.

    python3 -I tools/gen_preferences.py local/reference/renpy > src/rt/preference_tables.rs
"""
import ast
import re
import subprocess
import sys

repo = sys.argv[1]
tags = subprocess.run(["git", "-C", repo, "tag"], capture_output=True, text=True, check=True).stdout.split()
best = {}
for t in tags:
    m = re.match(r"^([78])\.(\d+)\.\d+", t)
    if not m:
        continue
    k = (int(m.group(1)), int(m.group(2)))
    key = tuple(int(x) for x in re.findall(r"\d+", t))
    if k not in best or key > best[k][0]:
        best[k] = (key, t)


def rs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


print("// SPDX-License-Identifier: MPL-2.0")
print("// Generated by tools/gen_preferences.py from Ren'Py renpy/preferences.py (MIT).")
print("// Do not edit.")
print("//! (major, minor, source tag, __version__ offset, [(name, default, types)]);")
print("//! defaults and types are Python expression source.")
print()
print("pub const TABLES: &[(u32, u32, &str, i64, &[(&str, &str, &str)])] = &[")
for (major, minor), (_, tag) in sorted(best.items()):
    src = subprocess.run(["git", "-C", repo, "show", f"{tag}:renpy/preferences.py"], capture_output=True, text=True, check=True).stdout
    tree = ast.parse(src)
    prefs = []
    offset = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call) and getattr(node.value.func, "id", None) == "Preference":
            a = node.value.args
            name = ast.literal_eval(a[0])
            default = ast.get_source_segment(src, a[1])
            types = ast.get_source_segment(src, a[2]) if len(a) > 2 else "type(" + default + ")"
            prefs.append((node.lineno, name, default, types))
        if isinstance(node, ast.ClassDef) and node.name == "Preferences":
            for b in node.body:
                if isinstance(b, ast.Assign) and getattr(b.targets[0], "id", None) == "__version__":
                    v = b.value
                    if isinstance(v, ast.BinOp):
                        offset = ast.literal_eval(v.right)
    prefs.sort()
    print(f"    ({major}, {minor}, {rs(tag)}, {offset}, &[")
    for _, name, default, types in prefs:
        print(f"        ({rs(name)}, {rs(default)}, {rs(types)}),")
    print("    ]),")
print("];")

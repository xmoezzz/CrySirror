fn expand(input: &[u8]) -> Result<[u8; 256]> {
    ensure!(
        !input.is_empty() && input.len() <= 320,
        "PAC3 key length must be 1..320"
    );
    let sum = input.iter().map(|v| *v as usize).sum::<usize>();
    let s = &SBOXES[sum % 4];
    let mut raw = [0u8; 320];
    raw[..input.len()].copy_from_slice(input);
    let mut buffer = [0u32; 80];
    for (i, p) in raw.chunks_exact(4).enumerate() {
        buffer[i] = u32::from_le_bytes(p.try_into()?);
    }
    for round in (4..80).step_by(4) {
        let mut prev = buffer[round - 1];
        for i in 0..4 {
            if (round + i) & 3 == 0 {
                let tmp = prev.rotate_left(8);
                let mut sub = 0u32;
                for j in 0..4 {
                    sub |= (s[((tmp >> (j * 8)) & 255) as usize] as u32) << (j * 8);
                }
                prev = ((1u32 << ((round + i) & 7)) | 0x30303000) ^ sub;
            }
            prev ^= buffer[round + i - 4];
            buffer[round + i] = prev;
        }
    }
    for (i, v) in buffer.iter().enumerate() {
        raw[i * 4..i * 4 + 4].copy_from_slice(&v.to_le_bytes());
    }
    let mut key = [0; 256];
    let mut at = 0;
    for i in 0..16 {
        for j in 0..=i {
            key[at] = raw[256 + i - j * 17];
            at += 1;
        }
    }
    for i in 0..15 {
        for j in 0..=14 - i {
            key[at] = raw[255 - i * 16 - j * 17];
            at += 1;
        }
    }
    Ok(key)
}
fn table_xor(b: &mut [u8], mut pos: usize, key: &[u8; 256]) {
    let mut at = 0;
    while at < b.len() {
        let n = (256 - pos % 256).min(b.len() - at);
        for i in 0..n {
            if i >= (n & !3) || i & 3 != 0 {
                b[at + i] ^= key[(pos + i) % 256];
            }
        }
        at += n;
        pos += n;
    }
}
fn file_keys(size: u64, name: &[u8], key: u32) -> Result<([u8; 256], [u8; 256])> {
    ensure!(!name.is_empty(), "PAC3 empty name key");
    let text = format!(
        "{:02}{:02}{:02}{:02}{:02}{:02}{:04X}",
        key & 0x3f,
        (key >> 6) & 0x3f,
        (key >> 12) & 15,
        (key >> 16) & 31,
        (key >> 21) & 15,
        (key >> 25) & 127,
        size as u16
    );
    let mut transient = [0u8; 16];
    for i in 0..16 {
        transient[i] = text.as_bytes()[i] ^ name[name.len() - 1 - i % name.len()];
    }
    let expanded = expand(&transient)?;
    let mut perm = std::array::from_fn(|i| i as u8);
    for tuple in expanded {
        perm.swap((tuple & 15) as usize, (tuple >> 4) as usize);
    }
    Ok((perm, expanded))
}
fn mix(source: &[u8; 256], marker: u8) -> [u8; 256] {
    let mut target = [0; 256];
    if marker == 0 {
        return *source;
    }
    if marker == 128 {
        for i in 0..256 {
            target[255 - i] = source[i];
        }
        return target;
    }
    let marker = marker as usize;
    let (mut tl, mut tr, mut sl, mut sr) = (marker as i32, 255 - marker as i32, 0i32, 255i32);
    for _ in 0..((255 - marker) / 2 + 1) {
        target[tl as usize] = source[sl as usize];
        target[tr as usize] = source[sr as usize];
        sl += 2;
        sr -= 2;
        tl += 2;
        tr -= 2;
    }
    tl -= 256;
    tr += 256;
    if marker > 1 {
        for _ in 0..((marker - 2) / 2 + 1) {
            target[tl as usize] = source[sl as usize];
            target[tr as usize] = source[sr as usize];
            sl += 2;
            sr -= 2;
            tl += 2;
            tr -= 2;
        }
    }
    target
}
pub(super) fn open(s: &dyn AssetReader, cx: &DecodeContext) -> Result<Vec<Row>> {
    ensure!(magic(s, 0, b"PAC3")?, "missing PAC3");
    let p = cx
        .parameters
        .get("almond-collective/pac3")
        .context("PAC3 needs caller key_id")?;
    let alias = p
        .get("key_id")
        .and_then(|v| v.as_str())
        .context("PAC3 key_id missing")?;
    let key = cx.keys.key(cx.client, alias)?.with_bytes(expand)?;
    let mut h = bytes(s, 4, 28, 28)?;
    table_xor(&mut h[..16], 4, &key);
    for at in (16..28).step_by(4) {
        table_xor(&mut h[at..at + 4], at + 4, &key);
    }
    let n = le32(&h, 16)? as usize;
    limits(cx, n)?;
    let table_size = le32(&h, 24)? as u64;
    let mut t = index(s, cx, 32, table_size)?;
    table_xor(&mut t, 32, &key);
    let mut c = Cursor::new(&t);
    let mut offset = 32 + table_size;
    let mut rows = Vec::new();
    for _ in 0..n {
        let id = c.le32()?;
        let size = c.le32()? as u64;
        c.take(4)?;
        let date = c.le32()?;
        let n = c.u8()? as usize;
        let name = zstr(c.take(n)?).to_vec();
        let path = sjis(&name)?;
        let (perm, expanded) = file_keys(size, &name, date)?;
        let off = offset;
        rows.push(
            Row::packed(
                path,
                off,
                size,
                size,
                decode(move |b, _| {
                    let mut out = b.to_vec();
                    let mut marker = (off >> 16) as u8;
                    let mut key2 = mix(&expanded, marker);
                    for (i, v) in out.iter_mut().enumerate() {
                        let pos = off + i as u64;
                        let wanted = (pos >> 16) as u8;
                        if marker != wanted {
                            marker = wanted;
                            key2 = mix(&expanded, marker);
                        }
                        *v ^= perm[((pos >> 8) & 255) as usize] ^ key2[(pos & 255) as usize];
                    }
                    Ok(out)
                }),
            )
            .meta(serde_json::json!({"file_id":id})),
        );
        offset = offset
            .checked_add(size)
            .context("PAC3 data offset overflow")?;
    }
    checked_rows(s, cx, rows)
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn native_fixture_crosses_key_blocks() {
        let cx_client = crysirror_core::state::ClientId(50);
        let mut cx = DecodeContext::new(cx_client);
        let keys = crysirror_resource::MemoryKeyProvider::default();
        keys.insert(cx_client, "fixture", b"self-authored".to_vec())
            .unwrap();
        cx.keys = Arc::new(keys);
        cx.parameters.insert(
            "almond-collective/pac3".into(),
            serde_json::json!({"key_id":"fixture"}),
        );
        let body: Vec<u8> = (0..0x10230).map(|i| (i * 13 + 7) as u8).collect();
        let name = b"fixture.bin";
        let date: u32 = 0x12345678;
        let expanded = expand(b"self-authored").unwrap();
        let mut table = 7u32.to_le_bytes().to_vec();
        table.extend((body.len() as u32).to_le_bytes());
        table.extend([0; 4]);
        table.extend(date.to_le_bytes());
        table.push(name.len() as u8);
        table.extend(name);
        let data_at = 32 + table.len();
        let mut h = vec![0; 28];
        h[16..20].copy_from_slice(&1u32.to_le_bytes());
        h[24..28].copy_from_slice(&(table.len() as u32).to_le_bytes());
        table_xor(&mut h[..16], 4, &expanded);
        for at in (16..28).step_by(4) {
            table_xor(&mut h[at..at + 4], at + 4, &expanded);
        }
        table_xor(&mut table, 32, &expanded);
        let (perm, key) = file_keys(body.len() as u64, name, date).unwrap();
        let mut stored = body.clone();
        for (i, v) in stored.iter_mut().enumerate() {
            let at = data_at + i;
            let mixed = mix(&key, (at >> 16) as u8);
            *v ^= perm[(at >> 8) & 255] ^ mixed[at & 255];
        }
        let mut bytes = b"PAC3".to_vec();
        bytes.extend(h);
        bytes.extend(table);
        bytes.extend(stored);
        let source: Arc<dyn AssetReader> =
            Arc::new(crysirror_core::service::MemoryAssetReader(Arc::from(bytes)));
        let format = super::super::FORMATS
            .iter()
            .find(|f| f.id == "almond-collective/pac3")
            .unwrap();
        let archive = crysirror_resource::ArchiveFormat::open(format, source, &cx).unwrap();
        assert_eq!(archive.entries()[0].path, "fixture.bin");
        let reader = archive.open(0, &cx).unwrap();
        assert_eq!(
            crysirror_resource::read_all(reader.as_ref(), 1 << 20).unwrap(),
            body
        );
    }
}
